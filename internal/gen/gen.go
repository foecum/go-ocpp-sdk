const header = "// Code generated by internal/gen201 from docs/spec/2.0.1/schemas; DO NOT EDIT.\n\n"

// node is one JSON schema node, with the keywords the OCPP 2.0.1 schemas use.
type node struct {
	Ref         string
	Type        string
	Format      string
	Description string
	Enum        []string
	MaxLength   *int
	MinItems    *int
	MaxItems    *int
	Minimum     *float64
	Maximum     *float64
	Items       *node
	Required    []string
	Props       []prop // in schema order
	hasType     bool
}

type prop struct {
	Name string
	Node *node
}

func (n *node) UnmarshalJSON(data []byte) error {
	var raw struct {
		Ref         string          `json:"$ref"`
		Type        *string         `json:"type"`
		Format      string          `json:"format"`
		Description string          `json:"description"`
		Enum        []string        `json:"enum"`
		MaxLength   *int            `json:"maxLength"`
		MinItems    *int            `json:"minItems"`
		MaxItems    *int            `json:"maxItems"`
		Minimum     *float64        `json:"minimum"`
		Maximum     *float64        `json:"maximum"`
		Items       *node           `json:"items"`
		Required    []string        `json:"required"`
		Properties  json.RawMessage `json:"properties"`
	}
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}
	*n = node{Ref: raw.Ref, Format: raw.Format, Description: raw.Description, Enum: raw.Enum, MaxLength: raw.MaxLength,
		MinItems: raw.MinItems, MaxItems: raw.MaxItems, Minimum: raw.Minimum, Maximum: raw.Maximum, Items: raw.Items, Required: raw.Required}
	if raw.Type != nil {
		n.Type, n.hasType = *raw.Type, true
	}
	if len(raw.Properties) > 0 {
		names, err := objectKeys(raw.Properties)
		if err != nil {
			return err
		}
		var byName map[string]*node
		if err := json.Unmarshal(raw.Properties, &byName); err != nil {
			return err
		}
		for _, name := range names {
			n.Props = append(n.Props, prop{name, byName[name]})
		}
	}
	return nil
}

// objectKeys returns the keys of a JSON object in document order.
func objectKeys(data []byte) ([]string, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	if _, err := dec.Token(); err != nil { // '{'
		return nil, err
	}
	var keys []string
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		key, ok := tok.(string)
		if !ok {
			return nil, errors.New("properties must be a JSON object")
		}
		keys = append(keys, key)
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return keys, nil
}

// canon returns a description-free fingerprint of n, to compare definitions.
func canon(n *node) string {
	if n == nil {
		return ""
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "{ref=%s type=%s/%v fmt=%s enum=%v max=%v minI=%v maxI=%v min=%v maxv=%v req=%v items=%s props=[",
		n.Ref, n.Type, n.hasType, n.Format, n.Enum, deref(n.MaxLength), deref(n.MinItems), deref(n.MaxItems),
		derefF(n.Minimum), derefF(n.Maximum), n.Required, canon(n.Items))
	for _, p := range n.Props {
		sb.WriteString(p.Name + ":" + canon(p.Node) + ";")
	}
	sb.WriteString("]}")
	return sb.String()
}

func deref(p *int) any {
	if p == nil {
		return nil
	}
	return *p
}

func derefF(p *float64) any {
	if p == nil {
		return nil
	}
	return *p
}

// message is a request/response schema pair.
type message struct {
	Name     string
	Request  *node
	Response *node
}

type gen struct {
	defs     map[string]*node // by schema definition name
	order    []string         // definition names, sorted
	goNames  map[string]string
	messages map[string]*message
	files    map[string][]byte
	blocks   []Block
}

// Generate reads the schemas in schemaDir and returns the generated files,
// keyed by path relative to the repository root.
func Generate(schemaDir string) (map[string][]byte, error) { return generate(schemaDir, Blocks) }

func generate(schemaDir string, blocks []Block) (map[string][]byte, error) {
	g := &gen{defs: map[string]*node{}, goNames: map[string]string{}, messages: map[string]*message{}, files: map[string][]byte{}, blocks: blocks}
	if err := g.load(schemaDir); err != nil {
		return nil, err
	}
	if err := g.nameTypes(); err != nil {
		return nil, err
	}
	if err := g.emitTypes(); err != nil {
		return nil, err
	}
	if err := g.emitBlocks(); err != nil {
		return nil, err
	}
	if err := g.emitHighLevel(); err != nil {
		return nil, err
	}
	return g.files, nil
}

func (g *gen) load(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	fingerprint := map[string]string{}
	for _, e := range entries {
		name := e.Name()
		if !strings.HasSuffix(name, ".json") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return err
		}
		var root struct {
			Definitions map[string]*node `json:"definitions"`
		}
		if err := json.Unmarshal(data, &root); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		var top node
		if err := json.Unmarshal(data, &top); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		for defName, def := range root.Definitions {
			fp := canon(def)
			if prev, seen := fingerprint[defName]; seen && prev != fp {
				return fmt.Errorf("%s: definition %s differs from its definition in another schema", name, defName)
			}
			if _, seen := fingerprint[defName]; !seen {
				fingerprint[defName] = fp
				g.defs[defName] = def
			}
		}
		base := strings.TrimSuffix(name, ".json")
		switch {
		case strings.HasSuffix(base, "Request"):
			msg := g.message(strings.TrimSuffix(base, "Request"))
			msg.Request = &top
		case strings.HasSuffix(base, "Response"):
			msg := g.message(strings.TrimSuffix(base, "Response"))
			msg.Response = &top
		default:
			return fmt.Errorf("%s: not a Request or Response schema", name)
		}
	}
	for _, m := range g.messages {
		if m.Request == nil || m.Response == nil {
			return fmt.Errorf("message %s lacks its request or its response schema", m.Name)
		}
	}
	for name := range g.defs {
		g.order = append(g.order, name)
	}
	sort.Strings(g.order)
	return nil
}

func (g *gen) message(name string) *message {
	m := g.messages[name]
	if m == nil {
		m = &message{Name: name}
		g.messages[name] = m
	}
	return m
}

// words splits a camelCase or PascalCase identifier into words, keeping runs of
// digits together: "iso15118SchemaVersion" gives iso, 15118, Schema, Version.
func words(s string) []string {
	var out []string
	var cur []rune
	flush := func() {
		if len(cur) > 0 {
			out = append(out, string(cur))
			cur = nil
		}
	}
	rs := []rune(s)
	for i, r := range rs {
		switch {
		case !unicode.IsLetter(r) && !unicode.IsDigit(r):
			flush()
		case unicode.IsUpper(r):
			prevLower := i > 0 && (unicode.IsLower(rs[i-1]) || unicode.IsDigit(rs[i-1]))
			acronymEnd := i > 0 && unicode.IsUpper(rs[i-1]) && i+1 < len(rs) && unicode.IsLower(rs[i+1])
			if prevLower || acronymEnd {
				flush()
			}
			cur = append(cur, r)
		case unicode.IsDigit(r):
			if len(cur) > 0 && !unicode.IsDigit(cur[len(cur)-1]) {
				flush()
			}
			cur = append(cur, r)
		default: // lower-case letter
			if len(cur) > 0 && unicode.IsDigit(cur[len(cur)-1]) {
				flush()
			}
			cur = append(cur, r)
		}
	}
	flush()
	return out
}

// goIdent turns a JSON name into an exported Go identifier, keeping the
// initialisms in capitals: "evseId" gives EVSEID.
func goIdent(s string) string {
	var sb strings.Builder
	for _, w := range words(s) {
		if up, ok := initialisms[strings.ToLower(w)]; ok {
			sb.WriteString(up)
			continue
		}
		rs := []rune(w)
		rs[0] = unicode.ToUpper(rs[0])
		sb.WriteString(string(rs))
	}
	return sb.String()
}

// typeName returns the Go name of a definition: the "Type" or "EnumType"
// suffix is dropped.
func typeName(def string) string {
	base := strings.TrimSuffix(strings.TrimSuffix(def, "EnumType"), "Type")
	if base == "" {
		base = def
	}
	return goIdent(base)
}

func (g *gen) nameTypes() error {
	used := map[string]string{}
	assign := func(def, name string) error {
		if other, clash := used[name]; clash {
			return fmt.Errorf("definitions %s and %s both become %s", other, def, name)
		}
		used[name] = def
		g.goNames[def] = name
		return nil
	}
	// Objects first; an enumeration whose name an object already has keeps its
	// "Enum" suffix (IdTokenType becomes IDToken, IdTokenEnumType IDTokenEnum).
	for _, def := range g.order {
		if def == "CustomDataType" || g.defs[def].Enum != nil {
			continue
		}
		if err := assign(def, typeName(def)); err != nil {
			return err
		}
	}
	for _, def := range g.order {
		if g.defs[def].Enum == nil {
			continue
		}
		name := typeName(def)
		if _, clash := used[name]; clash {
			name += "Enum"
		}
		if err := assign(def, name); err != nil {
			return err
		}
	}
	return nil
}

// refName extracts the definition name of a "#/definitions/X" reference.
func refName(ref string) string { return strings.TrimPrefix(ref, "#/definitions/") }

var (
	xrefWithText = regexp.MustCompile(`<<[^,>]*,([^>]*)>>`)
	xrefPlain    = regexp.MustCompile(`<<([^>]*)>>`)
)

// cleanDescription turns a schema description into plain text: it drops the
// label and URN lines, HTML entities and asciidoc cross references.
func cleanDescription(desc string) string {
	desc = html.UnescapeString(strings.ReplaceAll(desc, "\r", ""))
	desc = xrefWithText.ReplaceAllString(desc, "$1")
	desc = xrefPlain.ReplaceAllString(desc, "$1")
	var kept []string
	for i, line := range strings.Split(desc, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "urn:x-oca:") {
			continue
		}
		if i == 0 && strings.Contains(line, "_") && !strings.Contains(line, ".") && len(strings.Fields(line)) <= 4 {
			continue // a label such as "Charging_ Needs"
		}
		kept = append(kept, line)
	}
	return strings.Join(strings.Fields(strings.Join(kept, " ")), " ")
}

// comment renders a schema description as a Go comment with the given indent.
// The text starts with the identifier's name, as Go doc comments should.
func comment(indent, name, desc, fallback string) string {
	text := cleanDescription(desc)
	switch {
	case text == "":
		text = fallback
	case strings.HasPrefix(text, name+" "):
	case strings.HasPrefix(text, "The ") || strings.HasPrefix(text, "A ") || strings.HasPrefix(text, "An "):
		text = name + " is " + lowerFirst(text)
	default:
		text = name + ": " + text
	}
	return wrap(indent+"// ", text)
}

func lowerFirst(s string) string {
	rs := []rune(s)
	if len(rs) > 1 && unicode.IsUpper(rs[0]) && !unicode.IsUpper(rs[1]) {
		rs[0] = unicode.ToLower(rs[0])
	}
	return string(rs)
}

func wrap(prefix, text string) string {
	const width = 100
	var sb strings.Builder
	line := prefix
	for _, w := range strings.Fields(text) {
		if len(line)+len(w)+1 > width && line != prefix {
			sb.WriteString(strings.TrimRight(line, " ") + "\n")
			line = prefix
		}
		if line != prefix {
			line += " "
		}
		line += w
	}
	sb.WriteString(line + "\n")
	return sb.String()
}

// enumIdent builds the Go constant suffix for an enumeration value.
func enumIdent(v string) string {
	var sb strings.Builder
	for _, part := range strings.FieldsFunc(v, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		rs := []rune(part)
		rs[0] = unicode.ToUpper(rs[0])
		sb.WriteString(string(rs))
	}
	return sb.String()
}

func render(src string) ([]byte, error) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("generated code does not compile: %w\n%s", err, src)
	}
	return formatted, nil
}

