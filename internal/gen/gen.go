// Package gen generates the OCPP 2.0.1 Go types, messages and validation from
// the official JSON schemas in docs/spec/2.0.1/schemas.
//
// Generate returns the files to write; the test of this package checks that the
// committed files are exactly what Generate produces, and rewrites them when run
// with the -update flag:
//
//	go test ./internal/gen201 -run TestGeneratedCodeIsUpToDate -update
